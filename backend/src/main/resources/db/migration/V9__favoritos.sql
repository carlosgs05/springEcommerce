-- =============================================================================
-- V9__favoritos.sql  -  Agrega la tabla favorito (Dia 6: modulo Favoritos),
--         para que un usuario pueda marcar productos como favoritos sin
--         poder duplicar el mismo par usuario/producto.
-- =============================================================================
-- Que hace: CREATE TABLE public.favorito con PK propia, FK a usuario y a
--         producto, y una restriccion unica sobre (idusuario, idproducto).
-- NO toca: ninguna tabla ni columna de V1-V8.
-- Orden: despues de V8.
-- Filas existentes: no aplica, la tabla es nueva y nace vacia.
-- Repetible: no aplica el patron idempotente de scripts sueltos. Flyway no
--         permite reaplicar una version ya registrada en su historial
--         (flyway_schema_history), asi que esta migracion corre una sola vez
--         por base; no hace falta comprobar antes si la tabla ya existe.
-- Bloqueos: CREATE TABLE no bloquea nada existente (tabla nueva, sin filas).
-- Que debe verse: tabla favorito con columnas idfavorito (PK),
--         idusuario, idproducto, fecha_agregado, y la restriccion
--         uq_favorito_usuario_producto activa.
-- No es error: ningun aviso esperado en una corrida limpia.
-- Como se deshace: DROP TABLE public.favorito; (se pierden todos los
--         favoritos guardados, sin backup no se recuperan).
-- =============================================================================

CREATE TABLE public.favorito (
    idfavorito      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idusuario       INTEGER NOT NULL,
    idproducto      BIGINT NOT NULL,
    fecha_agregado  TIMESTAMP NOT NULL DEFAULT now()
);

ALTER TABLE public.favorito
    ADD CONSTRAINT favorito_idusuario_fkey FOREIGN KEY (idusuario) REFERENCES public.usuario(iduser);

ALTER TABLE public.favorito
    ADD CONSTRAINT favorito_idproducto_fkey FOREIGN KEY (idproducto) REFERENCES public.producto(idproducto);

ALTER TABLE public.favorito
    ADD CONSTRAINT uq_favorito_usuario_producto UNIQUE (idusuario, idproducto);
